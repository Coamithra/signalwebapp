// Regenerates public/emoji-shortcodes.js and public/emoji-tags.js from Signal
// Desktop's own emoji data. Two outputs, one script: they come from the same
// Signal install and must not drift apart across a Signal update.
//
// Signal ships build/emoji-data.json inside its app.asar: { emojis: { "🤷": {
// shortName: "shrug", shortNameAlts: [...], skinTones: {…} }, … } }. Reading it
// (instead of vendoring emoji-datasource, or hand-rolling a list) means our
// ":shortcode:" set is exactly the one Signal itself accepts — the same
// `:shrug:` you'd type in the real client. Keeps the app zero-dependency: the
// output is a plain JS module, checked in, so the running app never touches
// the asar.
//
// The *synonyms* ("chef" finding :cook:) come from a second Signal source, its
// localised emoji search index — the very list Signal's own picker searches.
// That one isn't in the asar: Signal downloads it on demand into its user-data
// optionalResources/ dir. We read the downloaded copy when it's there and
// otherwise fetch the URL out of the asar's own manifest, digest-verified.
//
//   node scripts/gen-emoji-map.mjs            # auto-detect the Signal install
//   node scripts/gen-emoji-map.mjs <app.asar> # or point at one
//
// Re-run after a Signal update to pick up new emoji.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';
import path from 'node:path';

const DEFAULT_ASARS = [
  process.env.LOCALAPPDATA && `${process.env.LOCALAPPDATA}/Programs/signal-desktop/resources/app.asar`,
  '/Applications/Signal.app/Contents/Resources/app.asar',
  '/opt/Signal/resources/app.asar',
].filter(Boolean);

// Read one file out of an asar archive (already-loaded buffer). Layout: a
// chromium Pickle header (4B pickle size, 4B header size, 4B object size, 4B
// JSON byte length) then the JSON directory, then the file data. The data
// section starts at 8 + headerSize — NOT 16 + jsonLength, which misses the
// pickle's 4-byte alignment padding and shifts every file by a few bytes.
function readFromAsar(buf, wanted) {
  const jsonLen = buf.readUInt32LE(12);
  const dataOffset = 8 + buf.readUInt32LE(4);
  const header = JSON.parse(buf.toString('utf8', 16, 16 + jsonLen));

  let node = header;
  for (const part of wanted.split('/').filter(Boolean)) {
    node = node.files?.[part];
    if (!node) throw new Error(`${wanted} not found in the archive`);
  }
  const start = dataOffset + Number(node.offset);
  return buf.toString('utf8', start, start + node.size);
}

const asarPath = process.argv[2] || DEFAULT_ASARS.find((p) => existsSync(p));
if (!asarPath) {
  console.error('Could not find Signal Desktop\'s app.asar. Pass its path as an argument.');
  process.exit(1);
}

const asar = readFileSync(asarPath); // a few hundred MB — read it once
const { emojis } = JSON.parse(readFromAsar(asar, '/build/emoji-data.json'));
const signalVersion = JSON.parse(readFromAsar(asar, '/package.json')).version;

// shortName -> emoji. Signal gives one canonical name per emoji; we add a few
// aliases people actually type (Signal's own names for these are unguessable:
// "+1", "-1"). Aliases never overwrite a canonical name.
const ALIASES = {
  thumbsup: '👍', thumbsdown: '👎', thumbs_up: '👍', thumbs_down: '👎',
  laughing: '😆', grinning: '😀', heart: '❤️', check: '✅', x: '❌',
};

const NAME_RE = /^[a-z0-9_+-]+$/;

const map = {};
for (const [emoji, meta] of Object.entries(emojis)) {
  const name = meta?.shortName;
  if (!name || !NAME_RE.test(name)) continue;
  if (!(name in map)) map[name] = emoji;
}
// Signal's own alternate shortcodes for the same emoji — ":poop:"/":shit:" for
// `hankey`, ":satisfied:" for `laughing`. Signal accepts these verbatim, so
// they're real shortcodes rather than mere search terms, and they belong in the
// map next to the canonical names. Canonical still wins on a collision.
let altCount = 0;
for (const [emoji, meta] of Object.entries(emojis)) {
  for (const alt of meta?.shortNameAlts || []) {
    if (!NAME_RE.test(alt) || alt in map) continue;
    map[alt] = emoji;
    altCount++;
  }
}
for (const [name, emoji] of Object.entries(ALIASES)) {
  if (!(name in map)) map[name] = emoji;
}

// Quote a key only when it isn't a bare identifier ("+1", "male-cook").
const key = (name) => (/^[a-z][a-z0-9_]*$/.test(name) ? name : JSON.stringify(name));

const sorted = Object.keys(map).sort();
const body = sorted.map((name) => `  ${key(name)}: ${JSON.stringify(map[name])},`).join('\n');

const out = `// GENERATED by scripts/gen-emoji-map.mjs from Signal Desktop's own
// build/emoji-data.json (Signal ${signalVersion}). Do not edit by hand;
// re-run the script after a Signal update.
//
// ":shortcode:" -> emoji. These are Signal's own shortcodes, so what you type
// here is what you'd type in the real client — including its own alternates
// (shortNameAlts), so ":poop:" works as well as ":hankey:".

export const EMOJI_SHORTCODES = Object.freeze({
${body}
});
`;

// ---------------------------------------------------------------------------
// Synonyms: Signal's localised emoji search index.
//
// [{ emoji:"🧑‍🍳", shortName:"cook", tags:["cook","chef"], rank:0 }, …] — the
// same list Signal's own emoji picker searches, which is where "chef" lives.
// Signal treats it as an *optional resource*: the asar carries only a manifest
// (url + size + sha512), and the JSON itself is downloaded into the user-data
// dir on demand. So prefer the downloaded copy, and fall back to fetching the
// manifest's url — a fresh install may not have pulled it yet.
const INDEX_FILE = 'emoji-index-en.json';

const SIGNAL_DATA_DIRS = [
  process.env.APPDATA && `${process.env.APPDATA}/Signal`,
  `${homedir()}/Library/Application Support/Signal`,
  process.env.XDG_CONFIG_HOME ? `${process.env.XDG_CONFIG_HOME}/Signal` : `${homedir()}/.config/Signal`,
].filter(Boolean);

async function loadSearchIndex() {
  const local = SIGNAL_DATA_DIRS
    .map((dir) => path.join(dir, 'optionalResources', INDEX_FILE))
    .find((p) => existsSync(p));
  if (local) return { json: JSON.parse(readFileSync(local, 'utf8')), from: local };

  const entry = JSON.parse(readFromAsar(asar, '/build/optional-resources.json'))[INDEX_FILE];
  if (!entry?.url) throw new Error(`${INDEX_FILE} is not in Signal's optional-resources manifest`);
  const res = await fetch(entry.url);
  if (!res.ok) throw new Error(`fetching ${entry.url} — HTTP ${res.status}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  // The manifest's digest is what Signal itself verifies the download against.
  const digest = createHash('sha512').update(bytes).digest('base64');
  if (digest !== entry.digest) throw new Error(`${entry.url} failed its sha512 check — refusing to generate from it`);
  return { json: JSON.parse(bytes.toString('utf8')), from: entry.url };
}

// A tag is a search term, not a shortcode: fold it into the charset a ":query"
// can actually contain, so "kitchen knife" is reachable as ":kitchen_knife".
const tagKey = (tag) => String(tag).toLowerCase().replace(/[^a-z0-9_+-]+/g, ' ').trim().replace(/\s+/g, '_');

const { json: index, from: indexFrom } = await loadSearchIndex();

const tags = {};
let kept = 0;
let skipped = 0;
for (const entry of index) {
  const name = entry?.shortName;
  // Guard the join: tags are keyed by shortName, so an index entry naming an
  // emoji we don't have (or a *different* emoji than we have under that name)
  // would hang synonyms off the wrong glyph.
  if (!name || map[name] !== entry.emoji) { skipped++; continue; }
  const seen = new Set();
  const list = [];
  for (const raw of entry.tags || []) {
    const tag = tagKey(raw);
    // Anything the name already contains is found by the name pass, at a better
    // rank than a tag could ever earn — carrying it here is dead weight.
    if (!tag || seen.has(tag) || name.includes(tag)) continue;
    seen.add(tag);
    list.push(tag);
  }
  if (!list.length) continue;
  tags[name] = list;
  kept += list.length;
}

const tagBody = Object.keys(tags).sort()
  .map((name) => `  ${key(name)}: [${tags[name].map((t) => JSON.stringify(t)).join(', ')}],`)
  .join('\n');

const tagOut = `// GENERATED by scripts/gen-emoji-map.mjs from Signal Desktop's own localised
// emoji search index (${INDEX_FILE}, Signal ${signalVersion}). Do not edit by
// hand; re-run the script after a Signal update.
//
// shortcode -> the synonyms Signal's own emoji picker searches, so ":chef"
// finds :cook:. Search terms only — these are NOT shortcodes and never expand.
// Tags already contained in their own shortcode are dropped (the name pass
// finds those), and spaces are folded to "_" so a multi-word tag stays typeable.

export const EMOJI_TAGS = Object.freeze({
${tagBody}
});
`;

// Both files last, once nothing is left that can fail. Loading the tag index can
// throw (no downloaded copy and no network, a bad digest), and writing the map
// before that would leave a freshly-regenerated emoji-shortcodes.js beside a
// stale emoji-tags.js still claiming the previous Signal version — the exact
// drift this script is one script to avoid.
const publicDir = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '../public');
writeFileSync(path.join(publicDir, 'emoji-shortcodes.js'), out);
console.log(`wrote emoji-shortcodes.js — ${sorted.length} shortcodes (${altCount} of them Signal's own alternates) from ${asarPath}`);
writeFileSync(path.join(publicDir, 'emoji-tags.js'), tagOut);
console.log(`wrote emoji-tags.js — ${kept} tags across ${Object.keys(tags).length} emoji from ${indexFrom}${skipped ? ` (${skipped} index entries skipped: no matching shortcode)` : ''}`);
